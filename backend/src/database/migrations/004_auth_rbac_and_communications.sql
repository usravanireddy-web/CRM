CREATE TABLE crm_roles (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_key VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL
);

CREATE TABLE crm_permissions (
  permission_key VARCHAR(80) PRIMARY KEY,
  description VARCHAR(180) NOT NULL
);

CREATE TABLE crm_role_permissions (
  role_id INTEGER NOT NULL REFERENCES crm_roles(id) ON DELETE CASCADE,
  permission_key VARCHAR(80) NOT NULL REFERENCES crm_permissions(permission_key) ON DELETE CASCADE,
  PRIMARY KEY (role_id, permission_key)
);

CREATE TABLE crm_users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id INTEGER NOT NULL REFERENCES crm_roles(id),
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(320) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE crm_leads ADD COLUMN owner_user_id INTEGER REFERENCES crm_users(id) ON DELETE SET NULL;
