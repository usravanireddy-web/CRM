-- Administrators receive every permission. Other roles receive only the permissions
-- needed for their workflow; authorization is enforced by the API on every request.
INSERT INTO crm_role_permissions(role_id, permission_key)
SELECT roles.id, permissions.permission_key
FROM crm_roles roles CROSS JOIN crm_permissions permissions
WHERE roles.role_key = 'admin';

