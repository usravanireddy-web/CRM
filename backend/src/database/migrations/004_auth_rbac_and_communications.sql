CREATE INDEX crm_leads_owner_user_id_idx ON crm_leads(owner_user_id);
CREATE INDEX crm_deals_owner_user_id_idx ON crm_deals(owner_user_id);
CREATE INDEX crm_tasks_assignee_user_id_idx ON crm_tasks(assignee_user_id);

