CREATE TABLE crm_email_campaigns (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(140) NOT NULL,
  subject VARCHAR(180) NOT NULL,
  body_text TEXT NOT NULL,
  recipients JSONB NOT NULL DEFAULT '[]'::jsonb,
  status VARCHAR(20) NOT NULL DEFAULT 'Draft' CHECK (status IN ('Draft', 'Sending', 'Sent')),
  created_by_user_id INTEGER NOT NULL REFERENCES crm_users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  sent_at TIMESTAMPTZ
);

CREATE TABLE crm_email_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id INTEGER REFERENCES crm_email_campaigns(id) ON DELETE SET NULL,
  sent_by_user_id INTEGER NOT NULL REFERENCES crm_users(id),
  recipient VARCHAR(320) NOT NULL,
  subject VARCHAR(180) NOT NULL,
  status VARCHAR(20) NOT NULL CHECK (status IN ('Sent', 'Failed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE crm_call_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES crm_users(id),
  contact_name VARCHAR(160) NOT NULL,
  phone VARCHAR(40) NOT NULL,
  outcome VARCHAR(40) NOT NULL,
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX crm_email_campaigns_created_at_idx ON crm_email_campaigns(created_at DESC);
CREATE INDEX crm_email_logs_user_id_idx ON crm_email_logs(sent_by_user_id, created_at DESC);
CREATE INDEX crm_call_logs_user_id_idx ON crm_call_logs(user_id, created_at DESC);
